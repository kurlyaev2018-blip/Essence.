    fun build(label: ImageLabel?): Essence {
        val raw = label?.labelName.orEmpty()
        val normalized = normalize(raw)

        if (normalized.isBlank()) {
            return Essence(
                title = "Не удалось распознать объект",
                steps = listOf(
                    "Подойди ближе, но не вплотную: 20–40 см обычно лучше.",
                    "Протри камеру и убери палец с объектива.",
                    "Включи свет или повернись к окну.",
                    "Сними объект целиком, а затем отдельным кадром — надпись, кнопку или деталь.",
                    "Если предмет может быть опасным: не трогай, не нюхай, не подключай к сети."
                )
            )
        }

        val matched = rules.firstOrNull { rule ->
            rule.keywords.any { keyword -> matches(normalized, keyword) }
        }

        return if (matched != null) {
            matched.essence.copy(title = "${matched.essence.title} • $raw")
        } else {
            generic(raw, label?.confidence ?: 0f)
        }
    }

    private fun normalize(value: String): String {
        return value.lowercase().trim().replace('_', ' ').replace('-', ' ')
    }

    private fun matches(text: String, keyword: String): Boolean {
        if (keyword.contains(' ')) return text.contains(keyword)
        val tokens = text.split(' ', ',', '.', '!', '?', ';', ':', '(', ')', '[', ']', '/', '\\', '"')
        return tokens.any { it == keyword }
    }

    private fun generic(label: String, confidence: Float): Essence {
        val percent = (confidence * 100).toInt().coerceIn(0, 100)
        return Essence(
            title = "Похоже на: $label ($percent%)",
            steps = listOf(
                "Уточни контекст: где предмет находится — кухня, авто, улица, магазин, ванная?",
                "Найди надписи, модель, штрихкод, QR-код, логотип и сфотографируй их отдельно.",
                "Если это еда, лекарство, химия или неизвестная жидкость: не пробуй и не смешивай.",
                "Если это электричество, транспорт, дети, животные или высота: сначала безопасность.",
                "Опиши словами, что видишь: материал, цвет, форма, кнопки, повреждения, запах."
            )
        )
    }
